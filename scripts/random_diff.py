#!/usr/bin/env python3
"""random_diff.py - random programs, checked instruction by instruction (Laxmidhar, G1).

    python scripts/random_diff.py                 # 20 random programs, both cores
    python scripts/random_diff.py -n 50 --seed 7  # 50 programs starting at seed 7
    python scripts/random_diff.py --workloads     # the C workloads instead of random code
    python scripts/random_diff.py --core ooo      # only one core

For each program:
  1. generate random RV32IM assembly (ALU, shifts, lui/auipc, MUL/DIV with
     edge values, loads/stores of every width, forward branches, counted
     loops, direct and indirect calls to leaf functions, and recursion deeper
     than the out-of-order core's 8-entry return-address stack)
  2. build it (Spike-comparison build: nothing timing-dependent)
  3. run it on the golden model (scripts/rv32im_iss.py) and on the simulated
     SoC with each core, all writing the same commit-log format
  4. compare every committed instruction: PC, instruction, register written,
     value, and load address. The first difference is printed.
ShieldV is on (SW0 = 1) the whole time, so every call and return is also
checked: a false alarm would freeze the core and show up as a difference.
The generated .S files are kept in build/random/ so a failure can be replayed.
"""
import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_sw     # noqa: E402
import run_prog     # noqa: E402
import rv32im_iss   # noqa: E402
import sim          # noqa: E402

POOL = ["x5", "x6", "x7", "x10", "x11", "x12", "x13", "x14", "x15", "x16", "x17", "x28", "x29", "x30"]
EDGE = [0, 1, -1, 2, -2, 0x7FFFFFFF, -0x80000000, 3, 7, 0x10000]
R_OPS = ["add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and"]
I_OPS = ["addi", "slti", "sltiu", "xori", "ori", "andi"]
SH_OPS = ["slli", "srli", "srai"]
M_OPS = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"]
BR_OPS = ["beq", "bne", "blt", "bge", "bltu", "bgeu"]
LOADS = [("lw", 4), ("lh", 2), ("lhu", 2), ("lb", 1), ("lbu", 1)]
STORES = [("sw", 4), ("sh", 2), ("sb", 1)]
N_LEAF = 3


class Gen:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.label = 0
        self.lines = []

    def reg(self):
        return self.r.choice(POOL)

    def new_label(self):
        self.label += 1
        return f"L{self.label}"

    def emit(self, s):
        self.lines.append("    " + s)

    def simple(self, allow_mem=True):
        """one straight-line instruction"""
        r, k = self.r, self.r.randrange(100)
        if k < 30:
            self.emit(f"{r.choice(R_OPS)} {self.reg()}, {self.reg()}, {self.reg()}")
        elif k < 50:
            self.emit(f"{r.choice(I_OPS)} {self.reg()}, {self.reg()}, {r.randint(-2048, 2047)}")
        elif k < 58:
            self.emit(f"{r.choice(SH_OPS)} {self.reg()}, {self.reg()}, {r.randint(0, 31)}")
        elif k < 62:
            self.emit(f"{r.choice(['lui', 'auipc'])} {self.reg()}, {r.randint(0, 0xFFFFF)}")
        elif k < 74:
            if r.random() < 0.3:                          # force an edge-case operand
                self.emit(f"li {self.reg()}, {r.choice(EDGE)}")
            self.emit(f"{r.choice(M_OPS)} {self.reg()}, {self.reg()}, {self.reg()}")
        elif k < 87 and allow_mem:
            op, size = r.choice(LOADS)
            self.emit(f"{op} {self.reg()}, {r.randrange(0, 256, size)}(s2)")
        elif allow_mem:
            op, size = r.choice(STORES)
            self.emit(f"{op} {self.reg()}, {r.randrange(0, 256, size)}(s2)")
        else:
            self.emit(f"add {self.reg()}, {self.reg()}, {self.reg()}")

    def program(self, items):
        r = self.r
        out = ["# generated by scripts/random_diff.py", "    .text", "    .globl main", "main:",
               "    addi sp, sp, -16", "    sw   ra, 12(sp)", "    sw   s2, 8(sp)", "    la   s2, rbuf"]
        self.lines = out
        for reg in POOL:
            self.emit(f"li {reg}, {r.randint(-2**31, 2**31 - 1)}")
        for _ in range(items):
            k = r.randrange(100)
            if k < 70:
                self.simple()
            elif k < 80:                                   # forward branch over 1-3 instructions
                end = self.new_label()
                self.emit(f"{r.choice(BR_OPS)} {self.reg()}, {self.reg()}, {end}")
                for _ in range(r.randint(1, 3)):
                    self.simple()
                self.lines.append(f"{end}:")
            elif k < 88:                                   # counted loop, x31 is the counter
                top = self.new_label()
                self.emit(f"li x31, {r.randint(2, 5)}")
                self.lines.append(f"{top}:")
                for _ in range(r.randint(2, 5)):
                    self.simple()
                self.emit("addi x31, x31, -1")
                self.emit(f"bnez x31, {top}")
            elif k < 95:                                   # direct call
                self.emit(f"jal ra, leaf{r.randrange(N_LEAF)}")
            elif k < 98:                                   # indirect call (jalr through x31)
                self.emit(f"la x31, leaf{r.randrange(N_LEAF)}")
                self.emit("jalr ra, 0(x31)")
            else:                                          # recursion deeper than the 8-entry RAS
                self.emit(f"li x31, {r.randint(9, 24)}")   # stays under the 32-entry shadow stack
                self.emit("jal ra, recurse")
        self.emit("lw   ra, 12(sp)")
        self.emit("lw   s2, 8(sp)")
        self.emit("addi sp, sp, 16")
        self.emit("li   a0, 0")
        self.emit("ret")
        for j in range(N_LEAF):                            # leaf functions: ALU only, then return
            self.lines.append(f"leaf{j}:")
            for _ in range(r.randint(1, 4)):
                self.simple(allow_mem=False)
            self.emit("ret")
        self.lines += ["recurse:", "    addi sp, sp, -16", "    sw   ra, 12(sp)", "    addi x31, x31, -1",
                       "    beqz x31, recurse_end", "    jal  ra, recurse", "recurse_end:",
                       "    lw   ra, 12(sp)", "    addi sp, sp, 16", "    ret"]
        self.lines += ["    .data", "    .balign 4", "rbuf:"]
        for _ in range(64):
            self.emit(f".word {r.randint(0, 2**32 - 1)}")
        return "\n".join(self.lines) + "\n"


def parse(path):
    import re
    pat = re.compile(r"0x([0-9a-f]+) \(0x([0-9a-f]+)\)(?: x(\d+) 0x([0-9a-f]+))?(?: mem 0x([0-9a-f]+))?")
    out = []
    with open(path) as f:
        for line in f:
            m = pat.search(line)
            if m:
                out.append(m.groups())
    return out


def compare(ref, rtl):
    """rtl must equal ref instruction by instruction; the testbench stops on the
    SIM_EXIT store, so it may miss the very last line or two."""
    for i, (a, b) in enumerate(zip(ref, rtl)):
        if a != b:
            return f"instruction {i}: golden {a} vs RTL {b}"
    if len(rtl) < len(ref) - 2:
        return f"RTL stopped early: {len(rtl)} of {len(ref)} instructions"
    return None


def check(prog, cores, simulator):
    out, _ = build_sw.build(prog, os.path.join(sim.BUILD, "sw_spike"), ["-DSPIKE_COMPARE"])
    golden = os.path.join(out, "golden.commit.log")
    code, n = rv32im_iss.run_files(os.path.join(out, "imem.hex"), os.path.join(out, "dmem.hex"), golden)
    ref = parse(golden)
    msgs = []
    for core in cores:
        result, _ = run_prog.run_one(prog, 1, simulator, log=True, quiet=True, spike=True, core=core,
                                     max_cycles=20 * n + 10000)
        tag = f"{prog}_sw1" + ("" if core == "inorder" else "_" + core)
        err = compare(ref, parse(os.path.join(out, tag + ".commit.log")))
        if not result.startswith("RESULT: EXIT 0"):
            err = (err or "") + f" [{result}]"
        msgs.append((core, err))
    return n, code, msgs


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-n", type=int, default=20, help="number of random programs")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--items", type=int, default=120, help="random items per program")
    ap.add_argument("--core", default="both", choices=["both"] + sorted(sim.CORES))
    ap.add_argument("--workloads", action="store_true", help="compare the C workloads instead")
    args = ap.parse_args()
    simulator = os.environ.get("SIM") or sim.default_sim()
    cores = sorted(sim.CORES) if args.core == "both" else [args.core]

    progs = []
    if args.workloads:
        progs = ["hello", "fib", "fact", "qsort", "bintree", "matmul", "primes", "hazards", "deep"]
    else:
        gen_dir = os.path.join(sim.BUILD, "random")
        os.makedirs(gen_dir, exist_ok=True)
        for seed in range(args.seed, args.seed + args.n):
            name = f"rand{seed}"
            path = os.path.join(gen_dir, name + ".S")
            with open(path, "w", newline="\n") as f:
                f.write(Gen(seed).program(args.items))
            build_sw.PROGRAMS[name] = [path]          # absolute path: build_sw uses it as is
            progs.append(name)

    fails = 0
    failed = []
    for prog in progs:
        n, code, msgs = check(prog, cores, simulator)
        bad = [m for m in msgs if m[1]]
        fails += bool(bad)
        if bad:
            failed.append(prog)
        status = "PASS" if not bad else "FAIL"
        print(f"{status}  {prog:10s} {n:7d} instructions  " +
              "  ".join(f"{c}: {'match' if not e else e}" for c, e in msgs))
    # The summary comes AFTER its own list. It names the program set and the
    # simulator, so two runs in one terminal cannot be mistaken for each other.
    kind = "C workloads" if args.workloads else "random programs"
    print(f"\n{len(progs) - fails}/{len(progs)} {kind} match the golden model on: {', '.join(cores)}"
          f" (simulator: {simulator})")
    if failed:
        print("FAILED: " + ", ".join(failed))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
